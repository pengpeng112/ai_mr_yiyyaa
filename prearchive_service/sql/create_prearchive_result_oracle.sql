-- 028 一期：归档前预检结果表（Oracle 生产应用库）
-- 红线：本脚本随代码交付但【不自动执行】；由 DBA 按 023 §9.1 批准单流程手工执行。
-- 命名沿用独立表前缀 MED_PREARCHIVE_*（与六类质控表零耦合，D5 隔离）。

CREATE TABLE MED_PREARCHIVE_RESULT (
    ID                   NUMBER(19)        NOT NULL,
    PATIENT_ID           VARCHAR2(64)      NOT NULL,
    VISIT_ID             VARCHAR2(32)      NOT NULL,
    FINISHED_DATE_TIME   DATE              NOT NULL,   -- 检查键之三：完成时间（A1 复检）
    CURRENT_FLAG         NUMBER(1)         DEFAULT 1   NOT NULL,  -- 1=最新一次检查
    DEPT_CODE            VARCHAR2(64)      DEFAULT ''  NOT NULL,
    DEPT_NAME            VARCHAR2(128)     DEFAULT ''  NOT NULL,
    PATIENT_NAME         VARCHAR2(128)     DEFAULT ''  NOT NULL,
    DOCTOR_ID            VARCHAR2(64)      DEFAULT ''  NOT NULL,
    DOCTOR_NAME          VARCHAR2(128)     DEFAULT ''  NOT NULL,
    RECEIVER_FALLBACK    NUMBER(1)         DEFAULT 0   NOT NULL,  -- 1=管床兜底
    PROBLEM_COUNT        NUMBER(10)        DEFAULT 0   NOT NULL,
    SEVERITY_TOP         VARCHAR2(16)      DEFAULT ''  NOT NULL,
    PROBLEMS_JSON        CLOB              DEFAULT '[]' NOT NULL, -- 问题清单 JSON 数组
    RULE_VERSION         VARCHAR2(64)      DEFAULT ''  NOT NULL,
    PUSH_WECOM_STATUS    VARCHAR2(16)      DEFAULT 'pending' NOT NULL,  -- 双通道去重字段
    PUSH_WECOM_AT        DATE,
    PUSH_WECOM_DETAIL    VARCHAR2(512)     DEFAULT ''  NOT NULL,
    PUSH_AGENT_STATUS    VARCHAR2(16)      DEFAULT 'pending' NOT NULL,  -- 双通道去重字段
    PUSH_AGENT_AT        DATE,
    PUSH_AGENT_DETAIL    VARCHAR2(512)     DEFAULT ''  NOT NULL,
    CREATED_AT           DATE              DEFAULT SYSDATE NOT NULL,
    UPDATED_AT           DATE              DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MED_PREARCHIVE_RESULT PRIMARY KEY (ID),
    CONSTRAINT UQ_PREARCHIVE_CHECK_KEY UNIQUE (PATIENT_ID, VISIT_ID, FINISHED_DATE_TIME),
    CONSTRAINT CK_PREARCHIVE_CURRENT CHECK (CURRENT_FLAG IN (0, 1))
);

COMMENT ON TABLE  MED_PREARCHIVE_RESULT IS '028 归档前预检结果（独立表，与六类质控零耦合）';
COMMENT ON COLUMN MED_PREARCHIVE_RESULT.FINISHED_DATE_TIME IS '检查键三列之一：jhemr.pat_visit.finished_date_time，完成时间更新即重检';
COMMENT ON COLUMN MED_PREARCHIVE_RESULT.CURRENT_FLAG      IS '1=该患者最新一次检查（复检后旧行置0保留）';
COMMENT ON COLUMN MED_PREARCHIVE_RESULT.PUSH_WECOM_STATUS IS '企微通道推送状态 pending/sent/failed/skipped，同一result至多sent一次';
COMMENT ON COLUMN MED_PREARCHIVE_RESULT.PUSH_AGENT_STATUS IS '弹窗助手通道状态，与企微通道独立去重';

CREATE INDEX IX_PREARCHIVE_CURRENT      ON MED_PREARCHIVE_RESULT (PATIENT_ID, VISIT_ID, CURRENT_FLAG);
CREATE INDEX IX_PREARCHIVE_PUSH_PENDING ON MED_PREARCHIVE_RESULT (PUSH_WECOM_STATUS);

-- ID 序列（Oracle 11g 无 identity 列时使用；12c+ 可改 GENERATED AS IDENTITY）
CREATE SEQUENCE SEQ_MED_PREARCHIVE_RESULT START WITH 1 INCREMENT BY 1 NOCACHE;
